#[tokio::test]
async fn receive_error_after_progress_is_delivered_on_next_read() {
    // A reset stream supplies a deterministic readable prefix followed by an
    // error, without requiring a privileged device or invalidating a live FD.
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let mut peer = TcpStream::connect(listener.local_addr().unwrap()).unwrap();
    let (stream, _) = listener.accept().unwrap();
    peer.write_all(b"prefix").unwrap();
    SockRef::from(&peer).set_linger(Some(Duration::ZERO)).unwrap();
    drop(peer);
    // SAFETY: ownership of a valid, open FD is transferred exactly once. This
    // test exercises only descriptor reads, not TUN-specific control operations.
    let device = unsafe { AsyncDevice::from_fd(stream.into_raw_fd()) }.unwrap();
    let mut reader = Reader::new(&device, 65535, true).unwrap();
    let mut packets = Vec::new();
    assert_eq!(reader.recv(&device, &mut packets).await.unwrap(), 1);
    assert_eq!(&packets[0][..], b"prefix");
    packets.clear();
    let error = timeout(Duration::from_secs(2), reader.recv(&device, &mut packets))
        .await.unwrap().unwrap_err();
    assert_eq!(error.kind(), io::ErrorKind::ConnectionReset);
}

/// Run with CAP_NET_ADMIN in an isolated network namespace. No default route
/// or host interfaces are changed; dropping the device removes its routes.
async fn kernel_udp_roundtrip(offload: bool) {
    let device = DeviceBuilder::new().name(if offload { "crs-batch-gso" } else { "crs-batch-plain" })
        .ipv4("198.18.77.1", 24, None).ipv6("fd00:198:18::1", 64)
        .mtu(1500).offload(offload).enable(true).build_async().unwrap();
    if offload { assert!(device.udp_gso(), "test kernel must support TUN UDP GSO"); }
    let mut reader = Reader::new(&device, 65535, true).unwrap();
    let mut writer = Writer::new(&reader, true).unwrap();
    for (bind, target) in [
        ("198.18.77.1:0", "198.18.77.2:5555"),
        ("[fd00:198:18::1]:0", "[fd00:198:18::2]:5555"),
    ] {
        let client = timeout(Duration::from_secs(5), async {
            loop {
                match UdpSocket::bind(bind).await {
                    Ok(socket) => break socket,
                    Err(error) if error.kind() == io::ErrorKind::AddrNotAvailable => {
                        tokio::time::sleep(Duration::from_millis(10)).await;
                    }
                    Err(error) => panic!("bind test client: {error}"),
                }
            }
        }).await.unwrap();
        let target: SocketAddr = target.parse().unwrap();
        // The kernel may deliver this as one UDP GSO frame. The device
        // reader must expose eight independent IP/UDP packets either way.
        let segment_size: libc::c_int = 64;
        // SAFETY: a live socket and c_int option with its exact length.
        assert_eq!(unsafe { libc::setsockopt(client.as_raw_fd(), libc::SOL_UDP,
            libc::UDP_SEGMENT, (&segment_size as *const libc::c_int).cast(),
            size_of::<libc::c_int>() as _) }, 0);
        let payload: Vec<u8> = (0..8).flat_map(|i| [i; 64]).collect();
        client.send_to(&payload, target).await.unwrap();
        let mut packets = Vec::new();
        timeout(Duration::from_secs(5), async {
            let mut incoming = Vec::new();
            while packets.len() < 8 {
                reader.recv(&device, &mut incoming).await.unwrap();
                for packet in incoming.drain(..) {
                    // Ignore IPv6 neighbor/router discovery generated by setup.
                    if parse_udp_packet(&packet).is_some_and(|(_, destination, _)| destination == target) {
                        packets.push(packet);
                    }
                }
            }
        }).await.unwrap();
        assert_eq!(packets.len(), 8);
        for (i, packet) in packets.iter().enumerate() {
            let (source, destination, range) = parse_udp_packet(packet).unwrap();
            assert_eq!((source, destination), (client.local_addr().unwrap(), target));
            assert_eq!(&packet[range], &[i as u8; 64]);
        }
        let (stack, _, udp) = NetStack::new();
        let (_, mut stack_read) = stack.split();
        let (_, mut send) = udp.split();
        let replies: Vec<_> = (0..16).map(|i| UdpPacket::from((
            Bytes::from(vec![i; if i == 15 { 0 } else { 64 }]), target, client.local_addr().unwrap(),
        ))).collect();
        assert_eq!(send.send_batch(&replies).unwrap(), 16);
        let mut outbound = Vec::new();
        for _ in 0..16 { outbound.push(stack_read.next().await.unwrap().unwrap().into_bytes()); }
        writer.send(&device, &outbound).await.unwrap();
        timeout(Duration::from_secs(5), async {
            let mut buffer = [0; 128];
            for i in 0..16 {
                let (len, source) = client.recv_from(&mut buffer).await.unwrap();
                assert_eq!(source, target);
                assert_eq!(&buffer[..len], &vec![i as u8; if i == 15 { 0 } else { 64 }]);
            }
        }).await.unwrap();
    }
}

